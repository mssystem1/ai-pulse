function preserveWhitespace(source: string, translated: string) {
  const leading = source.match(/^\s*/)?.[0] || "";
  const trailing = source.match(/\s*$/)?.[0] || "";
  return `${leading}${translated}${trailing}`;
}

export function localizeUiText(lang: Lang, source: string): string {
  if (lang === "en" || !source.trim()) return source;
  const trimmed = source.trim();
  const exact = ZH_EXACT[trimmed] || ZH_PRODUCT[trimmed];
  if (exact) return preserveWhitespace(source, exact);
  for (const [pattern, replacement] of ZH_PHRASES) {
    if (pattern.test(trimmed))
      return preserveWhitespace(source, trimmed.replace(pattern, replacement));
  }
  return source;
}

const textSource = new WeakMap<Text, string>();
const textApplied = new WeakMap<Text, string>();
const attributeSource = new WeakMap<Element, Map<string, string>>();
const attributeApplied = new WeakMap<Element, Map<string, string>>();
const LOCALIZED_ATTRIBUTES = ["aria-label", "title", "placeholder"] as const;

function excluded(node: Node) {
  const element = node.nodeType === Node.ELEMENT_NODE
    ? node as Element
    : node.parentElement;
  return Boolean(element?.closest("script,style,pre,code,textarea,[data-no-localize]"));
}

function translateTextNode(node: Text, lang: Lang) {
  if (excluded(node)) return;
  const current = node.nodeValue || "";
  const lastApplied = textApplied.get(node);
  if (!textSource.has(node) || current !== lastApplied)
    textSource.set(node, current);
  const source = textSource.get(node) || current;
  const next = localizeUiText(lang, source);
  textApplied.set(node, next);
  if (current !== next) node.nodeValue = next;
}

function translateElementAttributes(element: Element, lang: Lang) {
  if (excluded(element)) return;
  const sources = attributeSource.get(element) || new Map<string, string>();
  const applied = attributeApplied.get(element) || new Map<string, string>();
  for (const attribute of LOCALIZED_ATTRIBUTES) {
    const current = element.getAttribute(attribute);
    if (current == null) continue;
    if (!sources.has(attribute) || current !== applied.get(attribute))
      sources.set(attribute, current);
    const next = localizeUiText(lang, sources.get(attribute) || current);
    applied.set(attribute, next);
    if (current !== next) element.setAttribute(attribute, next);
  }
  attributeSource.set(element, sources);
  attributeApplied.set(element, applied);
}

function translateTree(root: Node, lang: Lang) {
  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root as Text, lang);
    return;
  }
  if (root.nodeType === Node.ELEMENT_NODE)
    translateElementAttributes(root as Element, lang);
  const walker = document.createTreeWalker(
    root,
    NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT,
  );
  let node = walker.nextNode();
  while (node) {
    if (node.nodeType === Node.TEXT_NODE) translateTextNode(node as Text, lang);
    else translateElementAttributes(node as Element, lang);
    node = walker.nextNode();
  }
}

/** Keeps legacy and async UI copy synchronized with the application language. */
export function useDocumentLocale(lang: Lang) {
  useLayoutEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    translateTree(document.body, lang);
    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === "characterData")
          translateTextNode(mutation.target as Text, lang);
        else if (mutation.type === "attributes")
          translateElementAttributes(mutation.target as Element, lang);
        else
          mutation.addedNodes.forEach((node) => translateTree(node, lang));
      }
    });
    observer.observe(document.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: [...LOCALIZED_ATTRIBUTES],
    });
    return () => observer.disconnect();
  }, [lang]);
}
